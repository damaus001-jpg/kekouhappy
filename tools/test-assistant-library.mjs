import assert from 'node:assert/strict';
import { emptyAssistantLibrary } from '../dist-electron/assistant-library-types.js';
import { buildAssistantContext, validateAssistantModule, safePackagePath } from '../dist-electron/assistant-library-core.js';

const library=emptyAssistantLibrary();
assert.equal(buildAssistantContext(library,[{text:'I am tired'}]),'');
library.modules.persona.text='PRIVATE LONG STORY';
library.modules.persona.aiText='Confirmed biography';
assert.equal(buildAssistantContext(library,[{text:'I am tired'}]),'');
library.modules.persona.enabled=true;
let context=buildAssistantContext(library,[{text:'I am tired'}],new Date('2026-10-10T18:00:00Z'));
assert.ok(context.includes('Confirmed biography'));assert.ok(!context.includes('PRIVATE LONG STORY'));
const entry=(id,date,status,text)=>({id,title:id,text,date,status,timeZone:'America/Los_Angeles',tags:[],media:[]});
library.modules.schedule.enabled=true;
library.modules.schedule.entries=[entry('future','2026-10-11','planned','future activity'),entry('old','2026-09-01','completed','OLD PRIVATE EVENT'),entry('cancelled','2026-10-10','cancelled','CANCELLED EVENT')];
library.modules.quotes.enabled=true;
library.modules.quotes.entries=[entry('comfort','','planned','If you are tired, take a break.'),entry('unrelated','','planned','UNRELATED RECIPE')];
context=buildAssistantContext(library,[{text:'I feel tired today'}],new Date('2026-10-10T18:00:00Z'));
assert.ok(context.includes('future activity'));assert.ok(context.includes('计划，不能说成已发生'));assert.ok(context.includes('take a break'));
assert.ok(!context.includes('OLD PRIVATE EVENT'));assert.ok(!context.includes('CANCELLED EVENT'));assert.ok(!context.includes('UNRELATED RECIPE'));
assert.equal(context,buildAssistantContext(library,[{text:'I feel tired today'}],new Date('2026-10-10T18:00:00Z')));
library.modules.quotes.entries=[entry('zh','','planned','今天好累就早点休息')];
assert.ok(buildAssistantContext(library,[{text:'工作好累啊'}]).includes('早点休息'));
for(const path of ['../secret','/absolute','C:/secret','media/../secret','media\\file','media//file'])assert.throws(()=>safePackagePath(path));
assert.equal(safePackagePath('media/example.png'),'media/example.png');
assert.throws(()=>validateAssistantModule({...library.modules.persona,entries:[entry('bad','2026-02-30','planned','')]}));
assert.throws(()=>validateAssistantModule({...library.modules.persona,entries:[{...entry('bad','','planned',''),timeZone:'Bad/Timezone'}]}));
assert.throws(()=>validateAssistantModule({...library.modules.persona,entries:[entry('duplicate','','planned',''),entry('duplicate','','planned','')]}));
assert.throws(()=>validateAssistantModule({...library.modules.persona,entries:[{...entry('bad','','planned',''),media:[{id:'../../key',name:'bad',mime:'image/png',caption:''}]}]}));
assert.throws(()=>validateAssistantModule({...library.modules.persona,aiText:'a'.repeat(24001)}));
console.log('assistant-library: opt-in, private-story exclusion, stable context, date/status filtering, bilingual retrieval, and import validation passed');
