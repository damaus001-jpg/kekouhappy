const {app,dialog}=require('electron');
const path=require('node:path');
const fs=require('node:fs/promises');
const assert=require('node:assert/strict');
const {randomUUID}=require('node:crypto');
const root=path.resolve(__dirname,'..');
const testRoot=path.join(root,'.tmp',`assistant-library-test-${randomUUID()}`);
app.setPath('userData',testRoot);
app.whenReady().then(async()=>{
  const service=await import('../dist-electron/assistant-library.js');
  const {emptyAssistantLibrary}=await import('../dist-electron/assistant-library-types.js');
  await fs.mkdir(testRoot,{recursive:true});
  let library=await service.readAssistantLibrary();
  library.modules.persona.aiText='PRIVATE BIOGRAPHY TEST';
  library.modules.persona.enabled=true;
  await service.saveAssistantModule('persona',library.modules.persona);
  assert.ok(!(await fs.readFile(path.join(testRoot,'assistant-library','library.enc'))).includes(Buffer.from('PRIVATE BIOGRAPHY TEST')));
  assert.equal((await service.readAssistantLibrary()).modules.persona.aiText,'PRIVATE BIOGRAPHY TEST');
  const input=path.join(testRoot,'quotes.json');
  const module=emptyAssistantLibrary().modules.quotes;
  module.entries=[{id:'fixture',title:'comfort',text:'I am here if you feel tired.',date:'',timeZone:'America/Los_Angeles',status:'planned',tags:['tired'],media:[]}];
  await fs.writeFile(input,JSON.stringify({schemaVersion:1,kind:'quotes',module}));
  dialog.showOpenDialog=async()=>({canceled:false,filePaths:[input]});
  library=await service.importAssistantModule('quotes',true);
  assert.equal(library.modules.quotes.entries.length,1);
  await service.importAssistantModule('quotes',true);
  assert.equal((await service.readAssistantLibrary()).modules.quotes.entries.length,1);
  dialog.showOpenDialog=async()=>({canceled:false,filePaths:[path.join(root,'src/assets/xiaozhi-assistant-transparent.png')]});
  library=await service.attachAssistantMedia('quotes','fixture');
  const media=library.modules.quotes.entries[0].media[0];
  assert.ok((await fs.stat(await service.assistantMediaPath(media.id))).size>0);
  await assert.rejects(service.assistantMediaPath('../outside'));
  const zip=path.join(testRoot,'quotes.zip');
  dialog.showSaveDialog=async()=>({canceled:false,filePath:zip});
  assert.equal(await service.exportAssistantModule('quotes'),true);
  await service.saveAssistantModule('quotes',emptyAssistantLibrary().modules.quotes);
  dialog.showOpenDialog=async()=>({canceled:false,filePaths:[zip]});
  library=await service.importAssistantModule('quotes',false);
  assert.equal(library.modules.quotes.entries[0].media[0].id,media.id);
  assert.equal(library.modules.quotes.enabled,false);
  const before=JSON.stringify(library);
  await fs.writeFile(input,'{"schemaVersion":1,"kind":"quotes","module":{"entries":[]}}');
  dialog.showOpenDialog=async()=>({canceled:false,filePaths:[input]});
  await assert.rejects(service.importAssistantModule('quotes',false));
  assert.equal(JSON.stringify(await service.readAssistantLibrary()),before);
  dialog.showOpenDialog=async()=>({canceled:true,filePaths:[]});
  assert.equal(await service.importAssistantModule('quotes',false),null);
  assert.equal(JSON.stringify(await service.readAssistantLibrary()),before);
  console.log('assistant-library-runtime: encrypted persistence, JSON merge, media, ZIP round trip, cancellation, and failed-import preservation passed');
  app.exit(0);
}).catch(error=>{console.error(error);app.exit(1);});
